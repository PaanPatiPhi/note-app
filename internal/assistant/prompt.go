var thaiShortWeekdays = [...]string{"อา.", "จ.", "อ.", "พ.", "พฤ.", "ศ.", "ส."}
var thaiShortMonths = [...]string{"ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."}

// thaiDateTime จัดรูปเวลาแบบที่ใช้ตอบใน LINE เช่น "อา. 18 ต.ค. 09:00"
// คำนวณในโค้ดเพราะโมเดลเล็กมักคิดวันในสัปดาห์ผิด
func thaiDateTime(t time.Time) string {
	t = t.In(bangkok)
	return fmt.Sprintf("%s %d %s %s", thaiShortWeekdays[t.Weekday()], t.Day(), thaiShortMonths[t.Month()-1], t.Format("15:04"))
}

// thaiDate คือ thaiDateTime แบบไม่มีเวลา ใช้กับนัดทั้งวัน (ไม่แปลง timezone เพราะเป็นวันที่ล้วน)
func thaiDate(t time.Time) string {
	return fmt.Sprintf("%s %d %s", thaiShortWeekdays[t.Weekday()], t.Day(), thaiShortMonths[t.Month()-1])
}

var thaiWeekdays = [...]string{"อาทิตย์", "จันทร์", "อังคาร", "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์"}

// buildUserMessage รวม context ที่เปลี่ยนทุกครั้งกับข้อความของผู้ใช้
func buildUserMessage(now time.Time, openLists []string, text string) string {
	var b strings.Builder
	b.WriteString("<context>\n")
	fmt.Fprintf(&b, "เวลาปัจจุบัน: %s (วัน%s)\n", now.Format(time.RFC3339), thaiWeekdays[now.Weekday()])
	if len(openLists) == 0 {
		b.WriteString("ลิสต์ที่ยังเปิดอยู่: (ไม่มี)\n")
	} else {
		fmt.Fprintf(&b, "ลิสต์ที่ยังเปิดอยู่: %s\n", strings.Join(quoteAll(openLists), ", "))
	}
	b.WriteString("</context>\n<message>\n")
	b.WriteString(text)
	b.WriteString("\n</message>")
	return b.String()
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = fmt.Sprintf("%q", s)
	}
	return out
}
