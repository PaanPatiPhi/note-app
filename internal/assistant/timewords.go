// timeWords คือคำที่บอกว่าผู้ใช้ระบุวันหรือเวลาเอง
// ใช้กันโมเดลเล็กแต่งเวลาเตือนขึ้นมาเองตอนผู้ใช้ไม่ได้บอก (เช่น "เตือนให้ซื้อพัดลม" → ตั้ง 12:00 เอง)
var timeWords = []string{
	// วัน
	"วันนี้", "คืนนี้", "พรุ่งนี้", "มะรืน",
	"จันทร์", "อังคาร", "พุธ", "พฤหัส", "ศุกร์", "เสาร์", "อาทิตย์",
	"สัปดาห์หน้า", "อาทิตย์หน้า", "เดือนหน้า", "ปีหน้า", "สุดสัปดาห์", "เสาร์อาทิตย์",
	// เดือน (ทั้งแบบเต็มและย่อ)
	"มกรา", "กุมภา", "มีนา", "เมษา", "พฤษภา", "มิถุนา", "กรกฎา", "สิงหา", "กันยา", "ตุลา", "พฤศจิกา", "ธันวา",
	"ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค.",
	// เวลา
	"โมง", "ทุ่ม", "เที่ยง", "บ่าย", "เช้า", "เย็น", "ค่ำ", "ดึก", "ตอนนี้",
	"ตีหนึ่ง", "ตีสอง", "ตีสาม", "ตีสี่", "ตีห้า", // ไม่ใช้ "ตี" เดี่ยวๆ เพราะเจอใน "ตีแบด", "ตีพิมพ์"
	"นาที", "ชั่วโมง", "ชม.", "น.",
	// อังกฤษ
	"today", "tonight", "tomorrow", "monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday",
}

// mentionsTime บอกว่าข้อความมีวันหรือเวลาที่ผู้ใช้ระบุเองหรือไม่
// ตัวเลขใดๆ ก็นับ (เช่น "9", "25/10", "14:30") เพราะในบริบทของการเตือนมักเป็นวัน/เวลา
func mentionsTime(text string) bool {
	lower := strings.ToLower(text)
	for _, r := range lower {
		if unicode.IsDigit(r) { // รวมเลขไทย ๐-๙
			return true
		}
	}
	for _, w := range timeWords {
		if strings.Contains(lower, w) {
			return true
		}
	}
	return false
}
